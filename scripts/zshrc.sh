#!/usr/bin/env bash
# oh-my-zsh 기본 템플릿에서 ~/.zshrc 를 생성한다.
#   1) 템플릿 복사  2) plugins 라인 치환  3) 공통 설정 block 추가
# 서버별 설정은 ~/.zshrc.local 에 두고 .zshrc 끝에서 source 한다.
source "$(dirname "$0")/lib.sh"

ZSH="${ZSH:-$HOME/.oh-my-zsh}"
template="$ZSH/templates/zshrc.zsh-template"
[ -f "$template" ] || die "oh-my-zsh 템플릿 없음: $template (oh-my-zsh.sh 먼저 실행)"

MARK="# generated by setup_env/scripts/zshrc.sh"
target="$HOME/.zshrc"

if [ -f "$target" ] && ! grep -qF "$MARK" "$target"; then
    bak="$target.bak.$(date +%Y%m%d%H%M%S)"
    warn "기존 .zshrc 백업: $bak"
    cp "$target" "$bak"
fi

plugins="git zsh-autosuggestions zsh-syntax-highlighting"

{
    echo "$MARK (직접 수정 말고 스크립트를 고치고 재실행할 것)"
    # 템플릿 내 절대경로/plugins 라인 치환
    sed -E \
        -e "s|^export ZSH=.*|export ZSH=\"\$HOME/.oh-my-zsh\"|" \
        -e "s|^plugins=\(.*\)|plugins=($plugins)|" \
        "$template"
    cat <<'BLOCK'

# ---- setup_env: common ----
export PATH="$HOME/.local/bin:$HOME/.pixi/bin:$PATH"

if command -v fzf >/dev/null 2>&1; then
    source <(fzf --zsh)
fi

if command -v herdr >/dev/null 2>&1; then
    source <(herdr completion zsh)
fi

alias lal="ls -alh"
# Ubuntu 는 bat 이 batcat 으로 설치됨
command -v batcat >/dev/null 2>&1 && alias bat="batcat"

# ---- 서버별 설정 (git 에 올리지 않음) ----
[ -f "$HOME/.zshrc.local" ] && source "$HOME/.zshrc.local"
BLOCK
} > "$target"
log "generated: $target"

if [ ! -f "$HOME/.zshrc.local" ]; then
    cp "$SETUP_ENV_DIR/configs/zshrc.local.example" "$HOME/.zshrc.local"
    log "created: ~/.zshrc.local (서버에 맞게 수정하세요)"
fi
